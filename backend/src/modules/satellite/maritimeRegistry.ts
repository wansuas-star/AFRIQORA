// In-memory dynamic custom AOIs registered by users during runtime
const CUSTOM_REGISTERED_AOIS: AfricanPortRegistryEntry[] = [];

export class AfricanMaritimeRegistry {
  public static getAllPorts(): AfricanPortRegistryEntry[] {
    return [...AFRICAN_PORT_REGISTRY, ...CUSTOM_REGISTERED_AOIS];
  }

  public static getPortById(id: string): AfricanPortRegistryEntry | undefined {
    return AfricanMaritimeRegistry.getAllPorts().find((p) => p.id === id);
  }

  public static findPortByBbox(bbox: GeoBoundingBox): AfricanPortRegistryEntry | undefined {
    const [qMinLon, qMinLat, qMaxLon, qMaxLat] = bbox;
    const centerLon = (qMinLon + qMaxLon) / 2;
    const centerLat = (qMinLat + qMaxLat) / 2;

    // 1. Exact or containment match within port's bounding box
    const exact = AfricanMaritimeRegistry.getAllPorts().find((p) => {
      const [pMinLon, pMinLat, pMaxLon, pMaxLat] = p.bbox;
      return (
        centerLon >= pMinLon &&
        centerLon <= pMaxLon &&
        centerLat >= pMinLat &&
        centerLat <= pMaxLat
      );
    });
    if (exact) return exact;

    // 2. Proximity match (within ~30km / 0.28 degrees of port center)
    let closestPort: AfricanPortRegistryEntry | undefined = undefined;
    let minDistanceSq = 0.28 * 0.28;

    for (const p of AfricanMaritimeRegistry.getAllPorts()) {
      const pCenterLon = p.coordinates.lon;
      const pCenterLat = p.coordinates.lat;
      const dLon = centerLon - pCenterLon;
      const dLat = centerLat - pCenterLat;
      const distSq = dLon * dLon + dLat * dLat;
      if (distSq < minDistanceSq) {
        minDistanceSq = distSq;
        closestPort = p;
      }
    }

    return closestPort;
  }

  public static searchPorts(filters: {
    query?: string;
    region?: AfricanMaritimeRegion;
    country?: string;
    category?: PortCategory;
    limit?: number;
  }): AfricanPortRegistryEntry[] {
    const { query, region, country, category, limit = 100 } = filters;
    const q = (query || '').trim().toLowerCase();

    const results = AfricanMaritimeRegistry.getAllPorts().filter((p) => {
      if (region && p.region !== region) return false;
      if (country && p.country.toLowerCase() !== country.toLowerCase()) return false;
      if (category && p.category !== category) return false;

      if (!q) return true;

      return (
        p.name.toLowerCase().includes(q) ||
        p.country.toLowerCase().includes(q) ||
        (p.city && p.city.toLowerCase().includes(q)) ||
        p.strategicSignificance.toLowerCase().includes(q) ||
        (p.shippingCorridor && p.shippingCorridor.toLowerCase().includes(q))
      );
    });

    return results.slice(0, limit);
  }

  public static getRegionsSummary(): Array<{
    region: AfricanMaritimeRegion;
    displayName: string;
    portCount: number;
    countries: string[];
  }> {
    const regionNames: Record<AfricanMaritimeRegion, string> = {
      NORTH_AFRICA: 'North Africa & Red Sea',
      WEST_AFRICA: 'West Africa & Atlantic Islands',
      CENTRAL_AFRICA_GULF_OF_GUINEA: 'Central Africa & Gulf of Guinea',
      EAST_AFRICA_HORN: 'East Africa & Horn of Africa',
      SOUTHERN_AFRICA: 'Southern Africa & Cape Corridors',
      INDIAN_OCEAN_ISLANDS: 'Indian Ocean Island Nations',
      INLAND_WATERWAYS: 'Inland African Waterways & Great Lakes',
    };

    const all = AfricanMaritimeRegistry.getAllPorts();
    const grouped: Record<string, { countries: Set<string>; count: number }> = {};

    for (const key of Object.keys(regionNames)) {
      grouped[key] = { countries: new Set(), count: 0 };
    }

    for (const port of all) {
      if (grouped[port.region]) {
        grouped[port.region].count++;
        grouped[port.region].countries.add(port.country);
      }
    }

    return Object.entries(regionNames).map(([region, displayName]) => ({
      region: region as AfricanMaritimeRegion,
      displayName,
      portCount: grouped[region].count,
      countries: Array.from(grouped[region].countries).sort(),
    }));
  }

  public static registerCustomAOI(custom: {
    name: string;
    country?: string;
    region?: AfricanMaritimeRegion;
    lat: number;
    lon: number;
    bbox?: GeoBoundingBox;
    strategicSignificance?: string;
    category?: PortCategory;
  }): AfricanPortRegistryEntry {
    const latSpan = 0.05;
    const lonSpan = 0.07;
    const bbox: GeoBoundingBox = custom.bbox || [
      Number((custom.lon - lonSpan).toFixed(4)),
      Number((custom.lat - latSpan).toFixed(4)),
      Number((custom.lon + lonSpan).toFixed(4)),
      Number((custom.lat + latSpan).toFixed(4)),
    ];

    const slug = custom.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
    const id = `custom-aoi-${slug}-${Date.now()}`;

    const entry: AfricanPortRegistryEntry = {
      id,
      name: custom.name,
      country: custom.country || 'Custom Maritime Zone',
      region: custom.region || 'WEST_AFRICA',
      category: custom.category || 'COASTAL_FISHING_ZONE',
      harborType: 'OPEN_ANCHORAGE',
      coordinates: { lat: custom.lat, lon: custom.lon },
      bbox,
      strategicSignificance: custom.strategicSignificance || 'User-defined dynamic maritime observation zone.',
      coverage: {
        sarCoverage: true,
        opticalCoverage: true,
        recommendedBand: 'Radar VV/VH CFAR Vessel Detection',
        defaultObservationMode: 'SAR_C_BAND',
      },
      operationalStatus: 'OPERATIONAL_LIVE',
    };

    CUSTOM_REGISTERED_AOIS.push(entry);
    return entry;
  }
}
